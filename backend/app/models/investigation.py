"""
Phase 15: Trusted AI Investigation Agents — Data Models
Implements bounded investigation objectives, tool permission governance,
evidence-grounded claims, multi-step investigation traces, and
Human-in-the-Loop (HITL) defensive action approval workflows.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class ToolPermission(str, Enum):
    READ_GRAPH_ENTITY = "READ_GRAPH_ENTITY"
    RETRIEVE_EVIDENCE = "RETRIEVE_EVIDENCE"
    LOOKUP_VULNERABILITY = "LOOKUP_VULNERABILITY"
    LOOKUP_ATTACK_D3FEND = "LOOKUP_ATTACK_D3FEND"
    VALIDATE_SIGMA_RULE = "VALIDATE_SIGMA_RULE"
    RECONSTRUCT_TIMELINE = "RECONSTRUCT_TIMELINE"
    CORRELATE_ASSET_SBOM = "CORRELATE_ASSET_SBOM"
    SIMULATE_ATTACK_PATH = "SIMULATE_ATTACK_PATH"


class InvestigationState(str, Enum):
    INIT = "INIT"
    VALIDATING = "VALIDATING"
    RETRIEVING = "RETRIEVING"
    PIVOTING = "PIVOTING"
    EVALUATING = "EVALUATING"
    REPORTING = "REPORTING"
    COMPLETED = "COMPLETED"
    ABSTAINED = "ABSTAINED"
    FAILED = "FAILED"


class InvestigationToolCall(BaseModel):
    call_id: str
    tool_name: str
    parameters: Dict[str, Any]
    permitted: bool = True
    execution_time_ms: float = 0.0
    status: Literal["success", "blocked_permission", "error"] = "success"
    result_summary: str = ""
    error_message: Optional[str] = None
    output_data: Optional[Dict[str, Any]] = None


class EvidenceGroundedClaim(BaseModel):
    """
    Evidence-grounded claim emitted by an AI investigation agent.
    Must strictly anchor to retrieved evidence, identifying confidence,
    uncertainty bounds, and potential contradictions.
    """
    claim_id: str
    claim_text: str
    subject: str
    predicate: str
    object: str
    supporting_evidence_refs: List[str] = Field(default_factory=list)
    contradicting_evidence_refs: List[str] = Field(default_factory=list)
    sources: List[str] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    confidence: float = Field(ge=0.0, le=1.0)
    uncertainty: float = Field(ge=0.0, le=1.0)
    reasoning_summary: str
    verification_state: Literal["verified", "supported_unverified", "insufficient_evidence", "disputed"]
    next_recommended_step: Optional[str] = None


class InvestigationStep(BaseModel):
    step_number: int
    state: InvestigationState
    description: str
    tool_calls: List[InvestigationToolCall] = Field(default_factory=list)
    pivots_considered: List[str] = Field(default_factory=list)
    pivots_selected: List[str] = Field(default_factory=list)
    findings: List[str] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class ActionRiskLevel(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class ActionApprovalStatus(str, Enum):
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    EXECUTED = "EXECUTED"


class HITLProposedAction(BaseModel):
    """
    Human-in-the-Loop defensive action proposal.
    Guarantees zero autonomous execution of environment-modifying operations.
    Requires explicit analyst review and recorded approval.
    """
    action_id: str
    tenant_id: str
    action_type: Literal[
        "BLOCK_IP_FIREWALL",
        "DEPLOY_SIGMA_DETECTION",
        "PATCH_VULNERABLE_PACKAGE",
        "ISOLATE_NETWORK_SEGMENT",
        "ENFORCE_MFA_POLICY",
        "REVOKE_CREDENTIALS"
    ]
    proposed_action: str
    rationale: str
    supporting_evidence: List[str] = Field(default_factory=list)
    potential_impact: str
    affected_assets: List[str] = Field(default_factory=list)
    risk_level: ActionRiskLevel = ActionRiskLevel.MEDIUM
    required_permission: str = "SOC_ANALYST_L2"
    approval_status: ActionApprovalStatus = ActionApprovalStatus.PENDING
    approver: Optional[str] = None
    approval_timestamp: Optional[str] = None
    audit_history: List[Dict[str, Any]] = Field(default_factory=list)
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class InvestigationReport(BaseModel):
    """
    Structured investigation report generated by the trusted AI orchestrator.
    Exportable, reproducible, and verifiable.
    """
    report_id: str
    tenant_id: str
    analyst_id: str
    objective: str
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    executive_summary: str
    timeline_summary: List[Dict[str, Any]] = Field(default_factory=list)
    entities_and_relationships: Dict[str, Any] = Field(default_factory=dict)
    grounded_claims: List[EvidenceGroundedClaim] = Field(default_factory=list)
    what_is_known: List[str] = Field(default_factory=list)
    what_is_unknown: List[str] = Field(default_factory=list)
    what_contradicts: List[str] = Field(default_factory=list)
    stale_evidence_warnings: List[str] = Field(default_factory=list)
    affected_assets: List[str] = Field(default_factory=list)
    detection_coverage: List[str] = Field(default_factory=list)
    suggested_defensive_actions: List[HITLProposedAction] = Field(default_factory=list)
    execution_steps: List[InvestigationStep] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    reproducibility_digest: str
    is_inconclusive: bool = False


class InvestigationRequest(BaseModel):
    tenant_id: str = "default_tenant"
    analyst_id: str = "analyst_sec_01"
    objective: str
    target_entity: str
    max_steps: int = Field(default=6, ge=1, le=15)
    max_tool_calls: int = Field(default=10, ge=1, le=25)
